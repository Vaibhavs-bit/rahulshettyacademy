package com.automation.tracker;

import com.automation.logging.FrameworkLogger;
import com.automation.utils.FileUtils;
import org.apache.logging.log4j.Logger;

import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayDeque;
import java.util.Deque;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Feeds automated test results into the standalone Test Case Tracker web app
 * (tools/testcase-tracker/) so execution status/history show up next to the manually
 * tracked test cases without needing a database or extra JSON library dependency.
 *
 * Why this class exists: the tracker UI is a plain HTML/JS page that can't read the
 * filesystem on its own, so results are written out as a small JS file
 * (execution-data.js) that the page includes directly - this keeps the tool working
 * when opened as a plain file:// page, with no server or build step required.
 */
public final class TestCaseTracker {

    private static final Logger logger = FrameworkLogger.getLogger(TestCaseTracker.class);
    private static final Path DATA_FILE = Path.of("tools", "testcase-tracker", "data", "execution-data.js");
    private static final int MAX_HISTORY = 20;

    private static final Map<String, TestRecord> RESULTS = new LinkedHashMap<>();

    private TestCaseTracker() {
        // utility class - no instances
    }

    /**
     * Records the outcome of one automated test and rewrites execution-data.js.
     *
     * @param automationKey fully qualified "ClassName#methodName" identifying the test,
     *                       matched against a test case's "automationKey" field in the tracker UI
     * @param status         "Pass", "Fail", or "Blocked"
     * @param durationMs     test duration in milliseconds
     * @param errorMessage   failure/skip reason, or null when the test passed
     */
    public static synchronized void recordResult(String automationKey, String status, long durationMs, String errorMessage) {
        String lastRun = Instant.now().toString();
        TestRecord record = RESULTS.computeIfAbsent(automationKey, k -> new TestRecord());
        record.status = status;
        record.lastRun = lastRun;
        record.durationMs = durationMs;
        record.errorMessage = errorMessage;
        record.history.addFirst(new HistoryEntry(lastRun, status, durationMs, errorMessage));
        while (record.history.size() > MAX_HISTORY) {
            record.history.removeLast();
        }
        writeDataFile();
    }

    private static void writeDataFile() {
        StringBuilder js = new StringBuilder();
        js.append("// Auto-generated by com.automation.tracker.TestCaseTracker after every test run.\n");
        js.append("// Do not edit manually - it is overwritten the next time the suite executes.\n");
        js.append("const EXECUTION_RESULTS = {\n");

        boolean firstRecord = true;
        for (Map.Entry<String, TestRecord> entry : RESULTS.entrySet()) {
            if (!firstRecord) {
                js.append(",\n");
            }
            firstRecord = false;
            TestRecord r = entry.getValue();
            js.append("  \"").append(escape(entry.getKey())).append("\": {\n");
            js.append("    \"status\": \"").append(escape(r.status)).append("\",\n");
            js.append("    \"lastRun\": \"").append(escape(r.lastRun)).append("\",\n");
            js.append("    \"durationMs\": ").append(r.durationMs).append(",\n");
            js.append("    \"errorMessage\": ").append(quoteOrNull(r.errorMessage)).append(",\n");
            js.append("    \"history\": [\n");
            boolean firstHistory = true;
            for (HistoryEntry h : r.history) {
                if (!firstHistory) {
                    js.append(",\n");
                }
                firstHistory = false;
                js.append("      { \"date\": \"").append(escape(h.date)).append("\", \"status\": \"")
                        .append(escape(h.status)).append("\", \"durationMs\": ").append(h.durationMs)
                        .append(", \"errorMessage\": ").append(quoteOrNull(h.errorMessage)).append(" }");
            }
            js.append("\n    ]\n");
            js.append("  }");
        }
        js.append("\n};\n");

        FileUtils.writeTextFile(DATA_FILE, js.toString());
        logger.debug("Updated test case tracker data: {}", DATA_FILE.toAbsolutePath());
    }

    private static String quoteOrNull(String value) {
        return value == null ? "null" : "\"" + escape(value) + "\"";
    }

    private static String escape(String value) {
        if (value == null) {
            return "";
        }
        return value.replace("\\", "\\\\")
                .replace("\"", "\\\"")
                .replace("\n", "\\n")
                .replace("\r", "");
    }

    private static final class TestRecord {
        String status;
        String lastRun;
        long durationMs;
        String errorMessage;
        final Deque<HistoryEntry> history = new ArrayDeque<>();
    }

    private static final class HistoryEntry {
        final String date;
        final String status;
        final long durationMs;
        final String errorMessage;

        HistoryEntry(String date, String status, long durationMs, String errorMessage) {
            this.date = date;
            this.status = status;
            this.durationMs = durationMs;
            this.errorMessage = errorMessage;
        }
    }
}
